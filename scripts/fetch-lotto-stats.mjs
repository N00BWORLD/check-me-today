// 동행복권 로또 6/45 역대 당첨 번호를 긁어 번호별 출현 횟수를 집계하고
// src/data/lotto-stats/kr645.ts 를 다시 쓴다. (미국 복권은 scripts/fetch-us-lotto-stats.mjs)
//
// 사용법:  node scripts/fetch-lotto-stats.mjs            (1회차부터 최신 회차까지)
//          node scripts/fetch-lotto-stats.mjs 1200 1245  (회차 범위 지정)
//
// - 사이트는 정적 배포라 실행 시 외부 호출을 하지 않으므로, 새 회차가 쌓이면 이 스크립트를
//   다시 돌려 데이터 파일을 갱신한 뒤 커밋한다.
// - 2025년 사이트 개편 이후 주소: /lt645/selectPstLt645Info.do?srchLtEpsd=<회차>
//   (옛 주소 common.do?method=getLottoNumber 는 홈으로 리다이렉트된다)
// - 보너스 번호는 집계에서 제외한다 (당첨 번호 6개만).

import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const API = "https://www.dhlottery.co.kr/lt645/selectPstLt645Info.do?srchLtEpsd=";
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) Chrome/120.0 Safari/537.36";
/** 동시에 보내는 요청 수 (서버에 부담 주지 않도록 작게) */
const CONCURRENCY = 6;
const RETRIES = 3;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA_FILE = path.join(__dirname, "..", "src", "data", "lotto-stats", "kr645.ts");

/** 한 회차를 받아 { round, date, numbers } 로 돌려준다. 없는 회차면 null */
async function fetchRound(round) {
  for (let attempt = 1; attempt <= RETRIES; attempt++) {
    try {
      const res = await fetch(API + round, { headers: { "User-Agent": UA } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const json = await res.json();
      const row = json?.data?.list?.[0];
      if (!row || row.ltEpsd !== round) return null;
      const numbers = [row.tm1WnNo, row.tm2WnNo, row.tm3WnNo, row.tm4WnNo, row.tm5WnNo, row.tm6WnNo].map(Number);
      if (numbers.some((n) => !(n >= 1 && n <= 45))) throw new Error(`번호 이상: ${numbers}`);
      const d = String(row.ltRflYmd); // YYYYMMDD
      return { round, date: `${d.slice(0, 4)}-${d.slice(4, 6)}-${d.slice(6, 8)}`, numbers, bonus: Number(row.bnsWnNo) };
    } catch (err) {
      if (attempt === RETRIES) throw new Error(`${round}회차 실패: ${err.message}`);
      await new Promise((r) => setTimeout(r, 800 * attempt));
    }
  }
  return null;
}

/** 최신 회차: 파라미터 없이 부르면 최신 회차가 온다 */
async function fetchLatestRound() {
  const res = await fetch(API, { headers: { "User-Agent": UA } });
  const json = await res.json();
  const latest = Number(json?.data?.list?.[0]?.ltEpsd);
  if (!latest) throw new Error("최신 회차를 알 수 없습니다");
  return latest;
}

async function main() {
  const start = Number(process.argv[2] ?? 1);
  const end = Number(process.argv[3] ?? (await fetchLatestRound()));
  console.log(`집계 범위: ${start} ~ ${end} 회차`);

  const results = [];
  let next = start;
  let done = 0;
  const worker = async () => {
    while (next <= end) {
      const round = next++;
      const row = await fetchRound(round);
      if (row) results.push(row);
      done++;
      if (done % 100 === 0) console.log(`  ${done}/${end - start + 1} 회차 완료`);
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  results.sort((a, b) => a.round - b.round);

  if (results.length !== end - start + 1) {
    const got = new Set(results.map((r) => r.round));
    const missing = [];
    for (let r = start; r <= end; r++) if (!got.has(r)) missing.push(r);
    throw new Error(`빠진 회차가 있습니다: ${missing.join(", ")}`);
  }

  // 번호별 출현 횟수 (인덱스 1~45)
  const counts = new Array(46).fill(0);
  /** 번호별 마지막으로 나온 회차 (한 번도 안 나왔으면 0) */
  const lastRound = new Array(46).fill(0);
  /** 번호별 마지막으로 나온 날짜 */
  const lastDate = new Array(46).fill("");
  for (const r of results) {
    for (const n of r.numbers) {
      counts[n]++;
      lastRound[n] = r.round;
      lastDate[n] = r.date;
    }
  }
  const first = results[0];
  const latest = results[results.length - 1];

  const fmtRow = (arr, quote = false) => {
    // 10개씩 줄바꿈해 읽기 쉽게
    const lines = [];
    for (let i = 1; i <= 45; i += 10) {
      lines.push("    " + arr.slice(i, i + 10).map((v) => (quote ? JSON.stringify(v) : String(v))).join(", ") + ",");
    }
    return lines.join("\n");
  };

  const file = `// <auto-generated> scripts/fetch-lotto-stats.mjs 가 만든 파일. 손으로 고치지 말 것
// kr645: ${first.round}회(${first.date}) ~ ${latest.round}회(${latest.date}), ${results.length}회 추첨, 당첨 번호 6개만 집계 (보너스 제외)
import type { LottoStats } from "../lotto-types";

export const kr645Stats: LottoStats = {
  game: "kr645",
  drawCount: ${results.length},
  baseRound: ${latest.round},
  baseDate: "${latest.date}",
  sinceDate: "${first.date}",
  source: "동행복권 (dhlottery.co.kr) 회차별 당첨 결과",
  counts: [
    0,
${fmtRow(counts)}
  ],
  lastRound: [
    0,
${fmtRow(lastRound)}
  ],
  lastDate: [
    "",
${fmtRow(lastDate, true)}
  ],
};
`;

  mkdirSync(path.dirname(DATA_FILE), { recursive: true });
  writeFileSync(DATA_FILE, file, "utf8");

  console.log(`완료: ${latest.round}회차(${latest.date})까지 ${results.length}회 집계 → ${path.relative(process.cwd(), DATA_FILE)}`);
  console.log("가장 많이 나온 번호:", [...Array(45).keys()].map((i) => i + 1).sort((a, b) => counts[b] - counts[a]).slice(0, 6).join(", "));
  console.log("가장 적게 나온 번호:", [...Array(45).keys()].map((i) => i + 1).sort((a, b) => counts[a] - counts[b]).slice(0, 6).join(", "));
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
