// 미국 파워볼·메가밀리언스 역대 당첨 번호를 뉴욕주 공개 데이터(data.ny.gov, Socrata API)에서 받아
// 번호별 출현 횟수를 집계하고 src/data/lotto-stats/us-powerball.ts, us-megamillions.ts 를 다시 쓴다.
//
// 사용법:  node scripts/fetch-us-lotto-stats.mjs
//
// - 현재 규칙이 시작된 날부터만 센다 (이전 규칙은 번호 범위가 달라 섞을 수 없다)
//   파워볼: 2015-10-07 부터 흰 공 1~69 + 파워볼 1~26
//   메가밀리언스: 2017-10-31 부터 흰 공 1~70 (메가볼은 2025-04 부터 1~24, 그 전 1~25)
// - 보조 공(파워볼·메가볼)은 세지 않는다. 본번호 5개만 집계한다.
// - 뉴욕주 복권 공개 데이터셋: Powerball d6yy-54nr, Mega Millions 5xaw-6ayf

import { writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = path.join(__dirname, "..", "src", "data", "lotto-stats");

const GAMES = [
  {
    id: "us-powerball",
    exportName: "usPowerballStats",
    dataset: "d6yy-54nr",
    since: "2015-10-07",
    max: 69,
    pick: 5,
    source: "New York State Open Data (data.ny.gov, Powerball Winning Numbers)",
  },
  {
    id: "us-megamillions",
    exportName: "usMegaMillionsStats",
    dataset: "5xaw-6ayf",
    since: "2017-10-31",
    max: 70,
    pick: 5,
    source: "New York State Open Data (data.ny.gov, Mega Millions Winning Numbers)",
  },
];

async function fetchAll(dataset, since) {
  const rows = [];
  const limit = 5000;
  for (let offset = 0; ; offset += limit) {
    const url =
      `https://data.ny.gov/resource/${dataset}.json?$limit=${limit}&$offset=${offset}` +
      `&$order=draw_date%20ASC&$where=draw_date%20>=%20'${since}'`;
    const res = await fetch(url, { headers: { Accept: "application/json" } });
    if (!res.ok) throw new Error(`HTTP ${res.status}: ${url}`);
    const page = await res.json();
    rows.push(...page);
    if (page.length < limit) break;
  }
  return rows;
}

function fmtRows(arr, max, quote = false) {
  const lines = [];
  for (let i = 1; i <= max; i += 10) {
    const chunk = arr.slice(i, i + 10).map((v) => (quote ? JSON.stringify(v) : String(v)));
    lines.push("    " + chunk.join(", ") + ",");
  }
  return lines.join("\n");
}

async function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  for (const g of GAMES) {
    const rows = await fetchAll(g.dataset, g.since);
    if (rows.length === 0) throw new Error(`${g.id}: 자료가 없습니다`);

    const counts = new Array(g.max + 1).fill(0);
    const lastDate = new Array(g.max + 1).fill("");
    let lastDrawDate = "";
    for (const row of rows) {
      const date = String(row.draw_date).slice(0, 10);
      // winning_numbers: 파워볼은 "흰공 5개 + 파워볼" 6개, 메가밀리언스는 흰공 5개 (mega_ball 은 별도 필드)
      const nums = String(row.winning_numbers).trim().split(/\s+/).map(Number).slice(0, g.pick);
      if (nums.length !== g.pick || nums.some((n) => !(n >= 1 && n <= g.max))) {
        throw new Error(`${g.id} ${date}: 번호 이상 ${row.winning_numbers}`);
      }
      for (const n of nums) {
        counts[n]++;
        lastDate[n] = date;
      }
      lastDrawDate = date;
    }

    const file = `// <auto-generated> scripts/fetch-us-lotto-stats.mjs 가 만든 파일. 손으로 고치지 말 것
// ${g.id}: ${g.since} ~ ${lastDrawDate}, ${rows.length}회 추첨, 본번호 ${g.pick}개(1~${g.max})만 집계
import type { LottoStats } from "../lotto-types";

export const ${g.exportName}: LottoStats = {
  game: "${g.id}",
  drawCount: ${rows.length},
  baseRound: null,
  baseDate: "${lastDrawDate}",
  sinceDate: "${g.since}",
  source: ${JSON.stringify(g.source)},
  counts: [
    0,
${fmtRows(counts, g.max)}
  ],
  lastRound: null,
  lastDate: [
    "",
${fmtRows(lastDate, g.max, true)}
  ],
};
`;
    const outPath = path.join(OUT_DIR, `${g.id}.ts`);
    writeFileSync(outPath, file, "utf8");
    const order = [...Array(g.max).keys()].map((i) => i + 1);
    console.log(`${g.id}: ${rows.length}회 (${g.since} ~ ${lastDrawDate}) → ${path.relative(process.cwd(), outPath)}`);
    console.log("  많이 나온:", [...order].sort((a, b) => counts[b] - counts[a]).slice(0, 6).join(", "));
    console.log("  적게 나온:", [...order].sort((a, b) => counts[a] - counts[b]).slice(0, 6).join(", "));
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
